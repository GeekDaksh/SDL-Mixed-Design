"""Content-hash the primary sources into MANIFEST.sha256.

Stage: S01 CODIFY
Spec:  docs/Build_Manual_v3.md §10 step 1
Status: implemented.
"""

from __future__ import annotations

import hashlib
import shutil
from dataclasses import dataclass
from pathlib import Path

MANIFEST_NAME = "MANIFEST.sha256"

#: sha256sum-compatible: "<hex>  <path>". Lines starting with '#' are ours, and are ignored
#: by `shasum -a 256 -c` as well, so the manifest stays checkable with standard tools.
SEPARATOR = "  "
COMMENT = "#"


class SourceNotFrozen(RuntimeError):
    """A source document is absent from the manifest, or its hash no longer matches.

    `s01_codify` refuses to load a rule backed by such a source. A clause read from an
    unhashed document cannot enter the registry as VERIFIED.
    """


@dataclass(frozen=True)
class ManifestEntry:
    """One frozen source: the path recorded and the digest recorded for it."""

    path: str
    sha256: str


def hash_file(path: Path) -> str:
    """Return the content hash of one primary source."""
    with path.open("rb") as handle:
        return hashlib.file_digest(handle, "sha256").hexdigest()


def adopt(library_file: Path, standards_dir: Path, target_name: str) -> Path:
    """Copy a PDF out of the shared library into standards/, and return its new path.

    The copy is the point: a frozen source must not be able to move or be re-exported
    out from under the registry. The library file stays where it is.
    """
    standards_dir.mkdir(parents=True, exist_ok=True)
    target = standards_dir / target_name
    if not library_file.is_file():
        raise FileNotFoundError(f"library file not found: {library_file}")
    if target.is_file() and hash_file(target) == hash_file(library_file):
        return target
    shutil.copy2(library_file, target)
    return target


def write_manifest(standards_dir: Path, entries: list[ManifestEntry]) -> Path:
    """Hash every adopted source into MANIFEST.sha256 and return the manifest path."""
    manifest = standards_dir / MANIFEST_NAME
    lines = [
        f"{COMMENT} Frozen primary sources. Generated by scripts/00_freeze_standards.py.",
        f"{COMMENT} Never edit by hand. Verify with: shasum -a 256 -c {MANIFEST_NAME}",
    ]
    lines += [f"{e.sha256}{SEPARATOR}{e.path}" for e in sorted(entries, key=lambda e: e.path)]
    manifest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return manifest


def read_manifest(manifest: Path) -> dict[str, str]:
    """Read the manifest as a mapping of recorded path to content hash."""
    if not manifest.is_file():
        return {}
    out: dict[str, str] = {}
    for line in manifest.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith(COMMENT):
            continue
        digest, _, path = line.partition(SEPARATOR)
        out[path.strip()] = digest.strip()
    return out


def is_frozen(source_file: str, manifest: Path, repo_root: Path) -> bool:
    """Whether this source is in the manifest and its bytes still match."""
    try:
        verify_source(source_file, manifest, repo_root)
    except (SourceNotFrozen, FileNotFoundError):
        return False
    return True


def verify_source(source_file: str, manifest: Path, repo_root: Path) -> str:
    """Raise unless this file's hash is present in, and matches, the manifest.

    Returns the recorded digest, so a caller can stamp it onto the rules it loads.
    """
    recorded = read_manifest(manifest)
    if source_file not in recorded:
        raise SourceNotFrozen(
            f"{source_file} is absent from {manifest.name}; "
            f"run scripts/00_freeze_standards.py"
        )
    path = repo_root / source_file
    if not path.is_file():
        raise SourceNotFrozen(
            f"{source_file} is recorded in {manifest.name} but the file is missing from disk"
        )
    actual = hash_file(path)
    if actual != recorded[source_file]:
        raise SourceNotFrozen(
            f"{source_file} does not match {manifest.name}: "
            f"recorded {recorded[source_file][:12]}…, found {actual[:12]}…"
        )
    return actual
